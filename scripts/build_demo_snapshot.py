"""
Regenerates app/demo_snapshot.json from a real Claude API call.

This is the ONLY script allowed to make a live Claude call for demo data —
everywhere else, DEMO_MODE must make zero Anthropic calls and need no API
key at all (see app/demo_snapshot.py, app/routes_extract.py). Run this by
hand, with a real ANTHROPIC_API_KEY set, any time app/demo_data.py's fixed
emails change. Nothing under app/ imports this file.

Usage:
    python scripts/build_demo_snapshot.py
"""

import json
import sys
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent.parent))

from phase1_extraction.extractor import Extractor

# Private helper, reused intentionally so this script can't drift out of
# sync with the fixed email list it's building a snapshot for — see
# app/demo_data.py.
from app.demo_data import _demo_emails

SNAPSHOT_PATH = Path(__file__).parent.parent / "app" / "demo_snapshot.json"


def build() -> dict:
    extractor = Extractor()
    snapshot = {
        "_meta": {
            "note": "Generated by scripts/build_demo_snapshot.py from a real Claude API call.",
            "generated_at": datetime.now(timezone.utc).isoformat(),
        }
    }

    print(f"{'message_id':<16} {'actionable':<11} {'confidence':<11} injection_suspected")
    for demo_email in _demo_emails():
        email_data = {"from": demo_email.from_address, "subject": demo_email.subject, "body": demo_email.body}
        # Every demo email is its own single-message thread.
        result = extractor.extract(email_data, thread_context="")
        snapshot[demo_email.message_id] = result
        print(
            f"{demo_email.message_id:<16} {str(result['actionable']):<11} "
            f"{result['confidence']:<11} {result.get('injection_suspected')}"
        )

    return snapshot


def main() -> None:
    snapshot = build()
    with open(SNAPSHOT_PATH, "w") as f:
        json.dump(snapshot, f, indent=2, sort_keys=False)
        f.write("\n")
    print(f"\nWrote {len(snapshot) - 1} demo email result(s) to {SNAPSHOT_PATH}")


if __name__ == "__main__":
    main()
